package io.github.assami.audit.port;

import io.github.assami.audit.model.AuditLog;
import io.github.assami.audit.model.AuditPage;
import io.github.assami.audit.model.AuditQuery;

import java.util.List;
import java.util.Optional;

/**
 * Hexagonal port — the only storage abstraction the library exposes.
 * <p>
 * All adapters (JPA, InMemory, future MongoDB…) must implement this interface.
 * Consumers who need a custom storage back-end can also provide a bean of this
 * type and it will be preferred via {@code @ConditionalOnMissingBean}.
 */
public interface AuditRepository {

    /**
     * Persist a new audit log entry.
     *
     * @param log the log to save (id is pre-generated by the caller)
     * @return the saved log (may differ from input if the adapter enriches it)
     */
    AuditLog save(AuditLog log);

    /**
     * Bulk-save multiple entries in a single operation.
     *
     * @param logs entries to save
     * @return saved entries in the same order
     */
    List<AuditLog> saveAll(List<AuditLog> logs);

    /**
     * Retrieve a single log by its identifier.
     *
     * @param id the log's UUID string
     * @return the log, or empty if not found / soft-deleted
     */
    Optional<AuditLog> findById(String id);

    /**
     * Cursor-based paged query with optional filters.
     *
     * @param query filtering + pagination criteria
     * @return a page of results with the next cursor
     */
    AuditPage findAll(AuditQuery query);

    /**
     * Soft-delete a log entry (sets {@code deleted_at}).
     *
     * @param id the log's UUID
     */
    void softDelete(String id);

    /**
     * GDPR erasure — wipe personal data from the payload and mark the row erased.
     *
     * @param id the log's UUID
     */
    void gdprErase(String id);

    /**
     * Count the total number of non-deleted entries.
     * Used for Micrometer gauge {@code audit.repository.size}.
     */
    long count();
}
